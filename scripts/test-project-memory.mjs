import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {DatabaseSync} from 'node:sqlite';
import vm from 'node:vm';
const source=readFileSync(new URL('../worker.js',import.meta.url),'utf8');
const block=source.split('// EURO5_MEMORY_START')[1].split('// EURO5_MEMORY_END')[0];
const context=vm.createContext({crypto:globalThis.crypto,TextEncoder,Response,URL,ALLOWED_ORIGINS:['https://ukrsedo.github.io'],cors:()=>({})});
const memory=vm.runInContext(block+'\nEuro5Memory',context);
const sqlite=new DatabaseSync(':memory:');
sqlite.exec(readFileSync(new URL('../migrations/0001_project_memory.sql',import.meta.url),'utf8'));
const db={prepare(sql){let args=[];return {bind(...a){args=a;return this},async run(){return sqlite.prepare(sql).run(...args)},async all(){return {results:sqlite.prepare(sql).all(...args)}}}}};
const admin={id:'alice',company:'euro5',role:'admin'},bob={id:'bob',company:'euro5',role:'editor'};
const old='2026-10-12T08:00:00.000Z',now='2026-10-23T08:00:00.000Z',cutoff='2026-10-13T08:00:00Z';
const record={kind:'buyer_note',recordKey:'buyer-1',buyerCode:'12345678',content:'Previous evidence',availableAt:old,sourceUrl:'https://example.com/old-source'};
await memory.save(db,record,admin,old);
await memory.save(db,{...record,content:'Future winner information',availableAt:now},admin,now);
await memory.save(db,{kind:'preference',recordKey:'format',content:'Alice preference'},admin,old);
await memory.save(db,{kind:'preference',recordKey:'format',content:'Bob preference'},bob,old);
await memory.save(db,{kind:'profile',recordKey:'company',content:'Company profile'},admin,old);
await memory.save(db,{...record,recordKey:'other-company'}, {...admin,company:'other'},old);
await memory.save(db,{kind:'decision',recordKey:'choice',tenderId:'UA-2026-10-13-123456-a',content:'Decision after cutoff'},admin,now);
const b={asOf:cutoff,buyerCode:'12345678',tenderId:'UA-2026-10-13-123456-a'};
const result=await memory.context(db,b,admin,now),texts=result.records.map(x=>x.content);
assert(texts.includes('Previous evidence'));assert(!texts.includes('Future winner information'));assert(texts.includes('Alice preference'));assert(!texts.includes('Bob preference'));assert(!texts.includes('Decision after cutoff'));
assert.equal(result.records.filter(x=>x.kind==='buyer_note').length,1);
const current=await memory.context(db,{...b,asOf:now},admin,now);
assert(current.records.some(x=>x.content==='Future winner information'));assert(!current.records.some(x=>x.content==='Previous evidence'));
assert(!(await memory.context(db,{...b,buyerCode:'87654321'},admin,now)).records.some(x=>x.kind==='buyer_note'));
assert.throws(()=>memory.normalize({...record,availableAt:old,sourceUrl:''},admin,now));
assert.throws(()=>memory.normalize({...record,availableAt:'2027-01-01T00:00:00Z'},admin,now));
assert.throws(()=>memory.normalize({...record,sourceUrl:'javascript:alert(1)'},admin,now));
assert.throws(()=>memory.normalize({kind:'profile',recordKey:'company',content:'Unauthorized'},bob,now));
assert.throws(()=>memory.normalize(record,{...bob,role:'reader'},now));
await assert.rejects(()=>memory.context(db,{...b,asOf:'2026-10-13'},admin,now));
await assert.rejects(()=>memory.context(db,{...b,asOf:'2099-10-13T00:00:00Z'},admin,now));
const token='a'.repeat(40),env={MEMORY_ENABLED:'1',EURO5_MEMORY_DB:db,MEMORY_USERS:JSON.stringify([{...admin,token_sha256:await memory.digest(token)}])};
const req=(path,auth,origin='https://ukrsedo.github.io')=>new Request('https://worker.example/memory/'+path,{method:'POST',headers:{Origin:origin,...(auth?{Authorization:'Bearer '+auth}:{}),'Content-Type':'application/json'},body:JSON.stringify(b)});
assert.equal((await memory.route(req('context'),env,'https://ukrsedo.github.io')).status,401);
assert.equal((await memory.route(req('context','x'.repeat(40)),env,'https://ukrsedo.github.io')).status,401);
assert.equal((await memory.route(req('context',token),env,'https://ukrsedo.github.io')).status,200);
assert.equal((await memory.route(req('context',token),{...env,MEMORY_ENABLED:'0'},'https://ukrsedo.github.io')).status,503);
assert.equal((await memory.route(req('context',token,'https://evil.example'),env,'https://evil.example')).status,403);
assert.equal((await memory.route(req('context',token),env,'https://ukrsedo.github.io')).headers.get('Cache-Control'),'no-store');
assert(source.includes('"Content-Type,Authorization"'));
console.log('Project memory: temporal versions, tenant/user isolation, evidence requirements, roles, auth, origins and disabled mode passed.');
